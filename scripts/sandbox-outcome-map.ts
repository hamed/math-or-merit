/**
 * Rebuild the sandbox's reference grid:
 *
 *   npx vite-node scripts/sandbox-outcome-map.ts
 *
 * The guided map keeps its denser teaching range in outcome-map.ts. This grid
 * covers stake 0–1 and levy 0–0.5 under the same versioned 100-person protocol.
 * Levy samples are uniformly spaced after the square-root axis transform.
 */
import { writeFileSync } from 'node:fs';
import { GUIDED_OUTCOME_PROTOCOL, runOutcome } from '../src/lib/research';

const STAKE_STEPS = 32;
const LEVY_STEPS = 30;
const MAX_LEVY = 0.5;
const STAKES = Array.from({ length: STAKE_STEPS + 1 }, (_, i) => i / STAKE_STEPS);
const LEVIES = Array.from({ length: LEVY_STEPS + 1 }, (_, i) =>
  MAX_LEVY * (i / LEVY_STEPS) ** 2);
const RUNS = 8;
const SEED = 20261013;

const started = Date.now();
let measuredRooms = 0;
const rows = LEVIES.map((levy, iy) => STAKES.map((stake, ix) => {
  // The room starts equal. With no stake it stays equal; without a levy,
  // any positive stake asymptotically condenses onto one of the N people.
  // (0, 0) belongs to the first case.
  if (stake === 0) return { participants: GUIDED_OUTCOME_PROTOCOL.n, gini: 0 };
  if (levy === 0) return {
    participants: 1,
    gini: (GUIDED_OUTCOME_PROTOCOL.n - 1) / GUIDED_OUTCOME_PROTOCOL.n,
  };
  let participants = 0;
  let gini = 0;
  for (let k = 0; k < RUNS; k++) {
    const seed = (SEED + (iy * STAKES.length + ix) * RUNS + k) >>> 0;
    const outcome = runOutcome({ ...GUIDED_OUTCOME_PROTOCOL, beta: stake, taxRate: levy, seed });
    participants += outcome.effectiveParticipants;
    gini += outcome.gini;
    measuredRooms++;
  }
  return { participants: participants / RUNS, gini: gini / RUNS };
}));

const out = `/**
 * Sandbox reference: ${RUNS} independent seeded rooms per interior setting, protocol v${GUIDED_OUTCOME_PROTOCOL.version}.
 * N = ${GUIDED_OUTCOME_PROTOCOL.n}, ${GUIDED_OUTCOME_PROTOCOL.trades} trades, levy every round, tail averaged.
 * At stake=0, the initially equal room stays equal. At levy=0 and stake>0,
 * the exact asymptotic limit is one owner (Gini ${(GUIDED_OUTCOME_PROTOCOL.n - 1) / GUIDED_OUTCOME_PROTOCOL.n}).
 * Generated by scripts/sandbox-outcome-map.ts. Interior values are finite-run estimates.
 */
export const MAP_STAKES: readonly number[] = [${STAKES.join(', ')}];
export const MAP_LEVIES: readonly number[] = [${LEVIES.join(', ')}];
export const MAP_RUNS = ${RUNS};
/** [levy][stake] */
export const MAP_PARTICIPANTS: readonly (readonly number[])[] = [
${rows.map((row) => `  [${row.map((point) => Number(point.participants.toPrecision(10))).join(', ')}],`).join('\n')}
];
/** [levy][stake], from the same runs and checkpoints. */
export const MAP_GINI: readonly (readonly number[])[] = [
${rows.map((row) => `  [${row.map((point) => Number(point.gini.toPrecision(10))).join(', ')}],`).join('\n')}
];
`;

writeFileSync('src/lib/research/sandboxOutcomeMap.ts', out);
console.log(`measured ${measuredRooms} rooms for ${STAKES.length * LEVIES.length} settings in ${((Date.now() - started) / 1000).toFixed(1)} s`);
